<?php
// Блок конфигурационных параметров
$host = 'MySQL-8.0';      // Адрес сервера БД
$db   = 'lab_db';         // Имя базы данных, созданной на предыдущих занятиях
$user = 'root';           // Имя пользователя СУБД по умолчанию
$pass = '';               // Пароль пользователя (в OSPanel по умолчанию пустой)
$charset = 'utf8mb4';     // Кодировка для корректного отображения кириллицы

// Формирование строки DSN (Data Source Name)
$dsn = "mysql:host=$host;dbname=$db;charset=$charset";

// Опции конфигурации драйвера PDO
$options = [
    // Режим генерации исключений при возникновении ошибок SQL
    PDO::ATTR_ERRMODE            => PDO::ERRMODE_EXCEPTION,
    // Установка формата выборки строк по умолчанию в виде ассоциативных массивов
    PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
    // Отключение эмуляции подготовленных выражений для повышения безопасности
    PDO::ATTR_EMULATE_PREPARES   => false,
];

try {
    // Создание экземпляра класса PDO для управления сессией связи с БД
    $pdo = new PDO($dsn, $user, $pass, $options);
} catch (PDOException $e) {
    // В случае критической ошибки останавливаем выполнение скрипта и выводим отладочный текст
    die("Критическая ошибка: Не удалось установить соединение с БД! Текст ошибки: " . $e->getMessage());
}
?>
